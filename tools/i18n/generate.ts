import { createHash } from 'node:crypto'
import type { ArgumentKind, Catalog, Contract } from './catalog.ts'

const argumentTypes: Readonly<Record<ArgumentKind, string>> = {
  text: 'string | number',
  number: 'number',
  date: 'Date | number',
  tag: 'RichTextValue<T>',
}

/** The keys of the privacy policy's and the terms' sections: long words every other page would carry for nothing. */
const legalPrefixes = ['legal.privacy.', 'legal.terms.'] as const
const isLegal = (key: string) => legalPrefixes.some((prefix) => key.startsWith(prefix))
const main = (catalog: Catalog): Catalog => Object.fromEntries(Object.entries(catalog).filter(([key]) => !isLegal(key)))
const legal = (catalog: Catalog): Catalog => Object.fromEntries(Object.entries(catalog).filter(([key]) => isLegal(key)))
const banner = '// Generated by bun run i18n:generate. Edit the reviewed catalogs, not this file.\n'
const catalogModule = (keys: 'MainKey' | 'LegalKey', catalog: Catalog) => `${banner}
import type { ${keys} } from './generated.ts'
export const catalog: Readonly<Record<${keys}, string>> = ${JSON.stringify(catalog, null, 2)}
`

export const generate = (en: Catalog, sl: Catalog, contracts: ReadonlyMap<string, Contract>) => {
  const declarations = [...contracts]
    .map(([key, contract]) => {
      const values = [...contract]
        .map(([name, kind]) => `readonly ${JSON.stringify(name)}: ${argumentTypes[kind]}`)
        .join(';')
      return `${JSON.stringify(key)}: ${values ? `{ ${values} }` : 'Readonly<Record<string, never>>'}`
    })
    .join('\n')
  // The rich-text node type is a parameter only messages with tags use; without them it is named unused.
  const node = [...contracts.values()].some((contract) => [...contract.values()].includes('tag')) ? 'T' : '_T'
  const catalogVersion = createHash('sha256').update(JSON.stringify({ en, sl })).digest('hex')
  return {
    'generated.ts': `${banner}
import type { FormatXMLElementFn } from 'intl-messageformat'
export type RichTextValue<T = string> = FormatXMLElementFn<T>
export interface MessageArgumentsByKey<${node} = string> { ${declarations} }
export type MessageKey = keyof MessageArgumentsByKey
/** The privacy policy's and the terms' own words, which only those pages load. */
export type LegalKey = Extract<MessageKey, \`${legalPrefixes[0]}\${string}\` | \`${legalPrefixes[1]}\${string}\`>
export type MainKey = Exclude<MessageKey, LegalKey>
export type MessageValues<K extends MessageKey, T = string> = MessageArgumentsByKey<T>[K]
export const catalogVersion = ${JSON.stringify(catalogVersion)}
`,
    // One module per language, so the browser loads only the language it shows; the legal pages' words are a module of
    // their own, loaded only on those pages (`loadCatalog`).
    'catalog-en.ts': catalogModule('MainKey', main(en)),
    'catalog-sl.ts': catalogModule('MainKey', main(sl)),
    'legal-en.ts': catalogModule('LegalKey', legal(en)),
    'legal-sl.ts': catalogModule('LegalKey', legal(sl)),
  }
}
