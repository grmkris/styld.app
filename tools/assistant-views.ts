/**
 * The assistant views (`apps/web/src/assistant`) as one self-contained HTML file, served to ChatGPT and
 * Claude as the MCP Apps resource `ui://styld/views-<hash>.html`. The build inlines its script and styles,
 * because hosts load the file into a sandboxed frame without network access, and the server bundles the
 * result as a generated module, so a deploy never builds the view.
 *
 *   bun tools/assistant-views.ts           rebuild and compare with the module (part of `bun run check`)
 *   bun tools/assistant-views.ts --write   rebuild and write the module after changing a view
 */
import { createHash } from 'node:crypto'
import { mkdtemp, readFile, rm, writeFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import path from 'node:path'

const root = path.resolve(import.meta.dir, '..')
const modulePath = path.join(root, 'packages/server/src/mcp/apps/AssistantViews.generated.ts')
/** Hosts fetch the file once per connection. Effect and the Foldkit runtime are most of it (about
 * 100 KB gzipped); growth past this needs a reason. */
const budgetBytes = 384 * 1024

const build = async (): Promise<string> => {
  const outDir = await mkdtemp(path.join(tmpdir(), 'styld-assistant-views-'))
  try {
    const child = Bun.spawn(
      ['bunx', 'vite', 'build', '--config', 'vite.assistant.config.ts', '--outDir', outDir, '--logLevel', 'error'],
      { cwd: path.join(root, 'apps/web'), stdout: 'inherit', stderr: 'inherit' },
    )
    if ((await child.exited) !== 0) throw new Error('The assistant view build failed')
    const script = await readFile(path.join(outDir, 'views.js'), 'utf8')
    const styles = await readFile(path.join(outDir, 'views.css'), 'utf8')
    // An inline script ends at the first `</script`; the bundle must not contain one.
    return [
      '<!doctype html><html><head><meta charset="utf-8">',
      '<meta name="viewport" content="width=device-width, initial-scale=1">',
      `<style>${styles.replaceAll('</style', '<\\/style')}</style></head>`,
      `<body style="margin:0"><div id="styld-view"></div><script>${script.replaceAll('</script', '<\\/script')}</script></body></html>`,
    ].join('')
  } finally {
    await rm(outDir, { recursive: true, force: true })
  }
}

const moduleFor = (html: string) => {
  const sha256 = createHash('sha256').update(html).digest('hex')
  return [
    '// Generated by `bun run assistant-views:generate` from apps/web/src/assistant. Do not edit.',
    `export const assistantViews = { sha256: '${sha256}', html: ${JSON.stringify(html)} } as const`,
    '',
  ].join('\n')
}

const html = await build()
const bytes = new TextEncoder().encode(html).byteLength
if (bytes > budgetBytes) throw new Error(`The assistant views are ${bytes} bytes; the budget is ${budgetBytes}`)
const expected = moduleFor(html)
if (process.argv.includes('--write')) {
  await writeFile(modulePath, expected)
  console.log(`Wrote ${path.relative(root, modulePath)} (${bytes} bytes of HTML)`)
} else {
  const actual = await readFile(modulePath, 'utf8').catch(() => '')
  if (actual !== expected) throw new Error('The assistant views changed; run `bun run assistant-views:generate`')
  console.log(`Assistant views match the source (${bytes} bytes of HTML)`)
}
