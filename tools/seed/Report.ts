import type { GarmentRecord } from './Garments.ts'
import { passes } from './Gate.ts'
import { dollars } from './Ledger.ts'
import type { Spec } from './Manifest.ts'

// What a run of the seed tells the operator: for the test batch, every picture beside its spec, the judge's verdict and
// the attempts, with the pass rates and what was spent; the page is shown on the tailnet with `preview`.

/** How a batch of garments went. */
export const batchSummary = (records: ReadonlyArray<GarmentRecord>) => ({
  specs: records.length,
  firstTry: records.filter((record) => record.attempts[0]?.passed === true).length,
  passed: records.filter((record) => record.status === 'passed').length,
  failed: records.filter((record) => record.status === 'failed').length,
  pictures: records.reduce((sum, record) => sum + record.attempts.filter(({ file }) => file !== '').length, 0),
  retries: records.reduce((sum, record) => sum + Math.max(0, record.attempts.length - 1), 0),
})
export type BatchSummary = ReturnType<typeof batchSummary>

const percent = (part: number, whole: number) => (whole === 0 ? '0%' : `${Math.round((part / whole) * 100)}%`)

/** The summary as lines for the terminal. */
export const summaryLines = (summary: BatchSummary, spend: { readonly muse: number; readonly judge: number }) => [
  `Specs ${String(summary.specs)}: passed ${String(summary.passed)}, failed ${String(summary.failed)}`,
  `First-try pass rate ${percent(summary.firstTry, summary.specs)}, final ${percent(summary.passed, summary.specs)}, retries ${String(summary.retries)}, pictures ${String(summary.pictures)}`,
  `Spent so far: Muse ${dollars(spend.muse)}, judge ${dollars(spend.judge)}, total ${dollars(spend.muse + spend.judge)}`,
]

const escaped = (text: string) =>
  text.replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;').replaceAll('"', '&quot;')

const verdictLine = (record: GarmentRecord['attempts'][number], spec: Spec) => {
  if (record.error !== null) return `<p class="bad">Muse drew nothing: ${escaped(record.error)}</p>`
  if (record.verdict === null) return '<p>Not judged yet.</p>'
  const { verdict } = record
  const facts = [
    `garments ${String(verdict.garments)}`,
    `type ${verdict.type ?? '—'}`,
    `colours ${verdict.colours.join(', ') || '—'}`,
    ...(['person', 'text', 'hanger', 'cropped'] as const).filter((flag) => verdict[flag]),
  ]
  return `<p class="${passes(verdict, spec) ? 'good' : 'bad'}">${record.judge ?? ''}: ${escaped(facts.join(' · '))}</p>${
    verdict.notes === '' ? '' : `<p class="note">${escaped(verdict.notes)}</p>`
  }`
}

const specCard = (record: GarmentRecord, spec: Spec) => `
<section class="spec ${record.status}">
  <h2>${escaped(spec.name)} <small>${escaped(spec.id)} · ${spec.type} · ${spec.colours.join('/')} · ${record.size} · ${record.status}</small></h2>
  <div class="attempts">${record.attempts
    .map(
      (attempt, index) => `
    <figure>
      ${attempt.file === '' ? '<div class="none">no picture</div>' : `<img src="pieces/${escaped(attempt.file)}" alt="${escaped(spec.name)}, attempt ${String(index + 1)}">`}
      <figcaption><b>Attempt ${String(index + 1)}</b>${verdictLine(attempt, spec)}
        <details><summary>Prompt</summary><pre>${escaped(attempt.prompt)}</pre></details></figcaption>
    </figure>`,
    )
    .join('')}
  </div>
</section>`

