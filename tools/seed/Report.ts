/** The rest of What's new for a new person, by their Show me: newest first, the boards for their choice first, then
 * those for everyone, then the others (Everything: newest first). */
export const restOrder = <B extends { readonly seedId: string; readonly audience: 'women' | 'men' | 'all' }>(
  published: ReadonlyArray<B>,
  choice: 'women' | 'men' | 'all',
) => {
  const newest = published.toReversed()
  const rank = (audience: B['audience']) => (choice === 'all' || audience === choice ? 0 : audience === 'all' ? 1 : 2)
  return newest.toSorted((a, b) => rank(a.audience) - rank(b.audience))
}

const tagsOf = (board: PlannedBoard, kind: string): ReadonlyArray<string> =>
  board.request.board.tags.filter((tag) => tag.kind === kind).map(({ value }) => value)

/** What a dry run shows of the boards: counts, the publish order, each board's garments and operation, and the first
 * twelve of What's new under each Show me. */
export const planLines = (plan: SeedPlan) => {
  const count = (pick: (board: PlannedBoard) => ReadonlyArray<string>): string => {
    const tally = new Map<string, number>()
    for (const board of plan.boards) for (const key of pick(board)) tally.set(key, (tally.get(key) ?? 0) + 1)
    return [...tally].map(([key, n]) => `${key} ${String(n)}`).join(', ')
  }
  return [
    `Boards: ${String(plan.boards.length)}; by audience: ${count((board) => [board.audience])}; by owner: ${count((board) => [board.owner])}`,
    `By season: ${count((board) => tagsOf(board, 'season'))}; by build: ${count((board) => [board.request.board.build])}`,
    ...plan.accounts.map(
      ({ account, garments }) => `${account.id} (${account.email}): ${String(garments.length)} garments`,
    ),
    'Publish order:',
    ...plan.boards.map(
      ({ seedId, audience, featured, request }, index) =>
        `  ${String(index + 1).padStart(2)} ${seedId} [${audience}${featured ? ', featured' : ''}] ${request.operationId}: ${[...(request.board.anchor === undefined ? [] : [`anchor ${request.board.anchor}`]), ...request.board.pieces].join(' ')}`,
    ),
    ...(['women', 'men', 'all'] as const).map(
      (choice) =>
        `First 12 for ${choice === 'all' ? 'Everything' : choice === 'women' ? "Women's" : "Men's"}: ${restOrder(
          plan.boards,
          choice,
        )
          .slice(0, 12)
          .map(({ seedId }) => seedId)
          .join(', ')}`,
    ),
  ]
}

/** The run's report, in Markdown: what it spent and did, each board's outcome and check, the garments that need a
 * look, and the admin calls still to make over the MCP (signed in as an admin). */
export const seedReport = (input: {
  readonly at: string
  readonly spend: { readonly muse: number; readonly judge: number; readonly cutout: number }
  readonly generated: number
  readonly imported: number
  readonly failedSpecs: ReadonlyArray<string>
  readonly needsALook: ReadonlyArray<string>
  readonly results: ReadonlyArray<BoardResult>
}) => {
  const tally = (outcome: BoardResult['outcome']) => input.results.filter((result) => result.outcome === outcome).length
  const total = input.spend.muse + input.spend.judge + input.spend.cutout
  return [
    `# House boards seed, ${input.at}`,
    '',
    `Spent so far: Muse ${dollars(input.spend.muse)}, judge ${dollars(input.spend.judge)}, cut-outs (estimate) ${dollars(input.spend.cutout)}, total ${dollars(total)}.`,
    `This run: ${String(input.generated)} generated, ${String(input.imported)} imported, ${String(tally('created'))} created, ${String(tally('updated'))} changed, ${String(tally('unchanged'))} unchanged, ${String(tally('skipped'))} skipped, ${String(tally('failed'))} failed.`,
    '',
    `Failed specs: ${input.failedSpecs.join(', ') || 'none'}. Garments that need a look: ${input.needsALook.join(', ') || 'none'}.`,
    '',
    '| board | owner | audience | outcome | visible | check | detail |',
    '| --- | --- | --- | --- | --- | --- | --- |',
    ...input.results.map(
      (result) =>
        `| ${result.seedId} | ${result.owner} | ${result.audience} | ${result.outcome} | ${result.visibility ?? ''} | ${result.check ?? ''} | ${result.detail.join('; ').replaceAll('|', '/')} |`,
    ),
    '',
    'Admin calls still to make (an admin assistant, over the MCP):',
    ...input.results
      .filter((result) => result.featured && result.boardId !== null)
      .map(
        (result) =>
          `- curation_feature { kind: "board", id: "${result.boardId ?? ''}", featured: true } (${result.seedId})`,
      ),
  ].join('\n')
}
